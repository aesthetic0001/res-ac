#!/usr/bin/env python3
"""Write ignored local sensor-agent configuration without exposing its token."""
import argparse
import getpass
import json
import os
from pathlib import Path
import re
from urllib.parse import urlsplit


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'private' / 'device.json')
    args = parser.parse_args()
    url = input('Backend HTTPS URL (include port if non-default): ').strip().rstrip('/')
    parsed = urlsplit(url)
    if parsed.scheme != 'https' or not parsed.hostname or parsed.username or parsed.password or parsed.path or parsed.query or parsed.fragment:
        parser.error('Use an HTTPS origin only, e.g. https://<public-IP>:<port>.')
    try:
        parsed.port
    except ValueError:
        parser.error('Invalid server port.')
    device_id = input('Device ID (from backend setup): ').strip()
    if not re.fullmatch(r'[A-Za-z0-9_-]{1,64}', device_id):
        parser.error('Invalid device ID.')
    token = getpass.getpass('Device token (hidden): ').strip()
    if len(token) < 32 or not re.fullmatch(r'[A-Za-z0-9_-]+', token):
        parser.error('Enter the device token generated by backend setup.')
    interval = input('Reporting interval in seconds [10]: ').strip() or '10'
    if not interval.isdigit() or not 2 <= int(interval) <= 3600:
        parser.error('Interval must be between 2 and 3600 seconds.')
    value = dict(server_url=url, device_id=device_id, device_token=token,
                 interval_seconds=int(interval), queue_limit=100,
                 ca_file='/etc/res-ac/ca-bundle.pem')
    args.output.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    temporary = args.output.with_suffix('.tmp')
    fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, 'w') as stream:
        os.fchmod(stream.fileno(), 0o600)
        json.dump(value, stream, indent=2)
        stream.write('\n')
    os.replace(temporary, args.output)
    print('Saved private device configuration. No credentials were printed.')
    print('The default private/ directory is ignored by Git. Do not commit this file.')


if __name__ == '__main__':
    main()
